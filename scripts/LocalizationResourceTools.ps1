Set-StrictMode -Version Latest

function Read-UiCatalogue([string] $Path) {
    $document = [System.Xml.Linq.XDocument]::Load($Path)
    $entries = [Collections.Generic.Dictionary[string, string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($node in $document.Root.Elements('data')) {
        $key = [string]$node.Attribute('name').Value
        $value = [string]$node.Element('value').Value
        if ($key -notmatch '^[A-Za-z][A-Za-z0-9_]*$') { throw "Invalid resource key: $key" }
        if (-not $entries.TryAdd($key, $value)) { throw "Duplicate resource key: $key" }
        if ([string]::IsNullOrWhiteSpace($value)) { throw "Empty resource: $key" }
        if (-not $node.Element('comment') -or [string]::IsNullOrWhiteSpace($node.Element('comment').Value)) {
            throw "Missing translation context: $key"
        }
    }
    return ,$entries
}

function Get-UiPlaceholderSignature([string] $Value, [string] $Key) {
    try { $null = [System.Text.CompositeFormat]::Parse($Value) }
    catch { throw "Malformed template: $Key" }
    $indexes = [Collections.Generic.SortedSet[int]]::new()
    for ($index = 0; $index -lt $Value.Length; $index++) {
        if ($Value[$index] -ne '{') { continue }
        if ($index + 1 -lt $Value.Length -and $Value[$index + 1] -eq '{') { $index++; continue }
        $match = [regex]::Match($Value.Substring($index), '^\{(\d+)')
        if ($match.Success) { $null = $indexes.Add([int]$match.Groups[1].Value) }
    }
    return [string]::Join(',', $indexes)
}

function Get-UiProjection([Collections.Generic.Dictionary[string, string]] $Catalogue, [object[]] $Mapping) {
    $values = [Collections.Generic.Dictionary[string, string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($item in $Mapping) {
        if (-not $Catalogue.ContainsKey($item.Key)) { throw "Unknown mapped key: $($item.Key)" }
        if (-not $values.TryAdd($item.Target, $Catalogue[$item.Key])) { throw "Duplicate WinUI target: $($item.Target)" }
    }
    $names = [string[]]@($values.Keys)
    [Array]::Sort($names, [StringComparer]::Ordinal)
    $lines = [Collections.Generic.List[string]]::new()
    $lines.Add('<?xml version="1.0" encoding="utf-8"?>')
    $lines.Add('<!-- Generated by scripts/Update-LocalizationResources.ps1. Edit SharedUI/Localization instead. -->')
    $lines.Add('<root>')
    $lines.Add('  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>')
    $lines.Add('  <resheader name="version"><value>2.0</value></resheader>')
    foreach ($name in $names) {
        $escapedName = [Security.SecurityElement]::Escape($name)
        $escapedValue = [Security.SecurityElement]::Escape($values[$name])
        $lines.Add("  <data name=`"$escapedName`" xml:space=`"preserve`"><value>$escapedValue</value></data>")
    }
    $lines.Add('</root>')
    return [string]::Join("`r`n", $lines) + "`r`n"
}
